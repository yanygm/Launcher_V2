using System;

namespace KartRider
{
    /// <summary>
    /// 挑战赛（模式 17）`GameControlPacket(state=3 / state=4)` 的官方负载（84 字节）。
    ///
    /// 来源：官服抓包第 1 盘（`_work/官服挑战赛抓包全解析.md` 6.2，导出脚本 `_work/ch_ctrl_cs.py`）。
    /// 结构按客户端反编译的读法（`_work/netdoc/client_io_full.txt:10551` `sub_141B3E680`）：
    ///   int state / int tick / int / int / byte flag / [flag==1 时多一个 int] / int / 40 字节表 / int×3 / 8 字节 / 1 字节
    /// 这些字段**没有加密**（只有帧级 XOR 和车辆规格块的 spec 混淆，后者与本包无关）。
    ///
    /// 用法：拷一份、把 `[8..11]` 改成服务端自己的 tick，其余原样发。
    /// </summary>
    public static class CampaignControlPayloads
    {
        /// <summary>state=3（本盘结束倒计时）。</summary>
        public static readonly byte[] State3 = new byte[]
        {
            0xB3, 0x06, 0xCB, 0x3A, 0x03, 0x00, 0x00, 0x00, 0x6B, 0xC8, 0xA0, 0x78,
            0x08, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x0D, 0x00, 0x00, 0x00, 0x0E, 0x00, 0x00, 0x00, 0x0F, 0x00, 0x00,
            0x00, 0x10, 0x00, 0x00, 0x00, 0x11, 0x00, 0x00, 0x00, 0x12, 0x00, 0x00,
            0x00, 0x13, 0x00, 0x00, 0x00, 0x14, 0x00, 0x00, 0x00, 0x15, 0x00, 0x00,
            0x00, 0x16, 0x00, 0x00, 0x00, 0x17, 0x00, 0x00, 0x00, 0x18, 0x00, 0x00,
            0x00, 0x19, 0x00, 0x71, 0x18, 0x14, 0x64, 0x76, 0x00, 0x00, 0x00, 0x77,
        };

        /// <summary>state=4（进结算界面）。</summary>
        public static readonly byte[] State4 = new byte[]
        {
            0xB3, 0x06, 0xCB, 0x3A, 0x04, 0x00, 0x00, 0x00, 0x32, 0xD4, 0xA0, 0x78,
            0x08, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x0D, 0x00, 0x00, 0x00, 0x0E, 0x00, 0x00, 0x00, 0x0F, 0x00, 0x00,
            0x00, 0x10, 0x00, 0x00, 0x00, 0x11, 0x00, 0x00, 0x00, 0x12, 0x00, 0x00,
            0x00, 0x13, 0x00, 0x00, 0x00, 0x14, 0x00, 0x00, 0x00, 0x15, 0x00, 0x00,
            0x00, 0x16, 0x00, 0x00, 0x00, 0x17, 0x00, 0x00, 0x00, 0x18, 0x00, 0x00,
            0x00, 0x19, 0x00, 0x71, 0x18, 0x14, 0x64, 0x76, 0x00, 0x00, 0x00, 0x77,
        };

        /// <summary>取指定 state 的模板（3/4 有货，其它返回 null）。</summary>
        public static byte[] For(uint state)
        {
            switch (state)
            {
                case 3: return State3;
                case 4: return State4;
                default: return null;
            }
        }

        /// <summary>拷一份模板并把 tick 写进 `[8..11]`（包 ID 在 `[0..3]`，state 在 `[4..7]`）。</summary>
        public static byte[] Build(uint state, uint tick)
        {
            byte[] tpl = For(state);
            if (tpl == null)
            {
                return null;
            }
            byte[] buf = new byte[tpl.Length];
            Buffer.BlockCopy(tpl, 0, buf, 0, tpl.Length);
            BitConverter.GetBytes(state).CopyTo(buf, 4);
            BitConverter.GetBytes(tick).CopyTo(buf, 8);
            return buf;
        }
    }
}
